"""Provenance registry: every input is recorded in data/sources.json and rendered to data/SOURCES.md."""
import json
from datetime import date
from pathlib import Path

REGISTRY = Path("data/sources.json")
MARKDOWN = Path("data/SOURCES.md")


def _load() -> dict:
    return json.loads(REGISTRY.read_text(encoding="utf-8")) if REGISTRY.exists() else {}


def record(item: str, value, url: str, how: str, verified: bool = True, as_of: str | None = None) -> None:
    """Upsert one provenance row and re-render SOURCES.md.

    Intuition: a single keyed registry means re-running the pipeline updates rows
    instead of duplicating them, and the provenance test can read it as JSON.
    """
    reg = _load()
    reg[item] = {"value": str(value), "url": url, "as_of": as_of or date.today().isoformat(),
                 "how": how, "verified": bool(verified)}
    REGISTRY.parent.mkdir(parents=True, exist_ok=True)
    REGISTRY.write_text(json.dumps(reg, indent=2), encoding="utf-8")
    render()


def render() -> None:
    """Write data/SOURCES.md as a markdown table from the registry."""
    reg = _load()
    lines = ["# Data sources", "",
             "Generated by `provenance.py` — every input used by the pipeline. "
             "Event-level sources (one URL per event) are in `data/events.csv`.", "",
             "| item | value / count | source URL | as-of date | how obtained | verified |",
             "|---|---|---|---|---|---|"]
    for k in sorted(reg):
        r = reg[k]
        lines.append(f"| {k} | {r['value']} | {r['url']} | {r['as_of']} | {r['how']} | {r['verified']} |")
    MARKDOWN.write_text("\n".join(lines) + "\n", encoding="utf-8")


def get(item: str) -> dict | None:
    """Return one registry row, or None."""
    return _load().get(item)
